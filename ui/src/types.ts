/**
 * Domain types shared by the bridge, the logic modules and the components.
 *
 * These mirror the Rust command contract. Fields the Rust side does not send
 * yet are optional rather than required, so a leaner payload degrades to a
 * quieter UI instead of a crash.
 */

export type Modality = "image" | "video" | "audio" | "3d";

export interface Route {
  id: string;
  provider: string;
  slug: string;
  /** Why this route is ordered where it is, from the registry. */
  note?: string;
  /** Can this route actually run — key present *and* a client implemented. */
  available?: boolean;
  /** Why not, when it cannot. */
  unavailableReason?: string;
  /**
   * ISO `YYYY-MM-DD` this route's price was read, when it rests on a
   * promotional/launch rate the provider will revert. Absent for a permanent
   * rate.
   */
  promoAsOf?: string;
}

/**
 * What one model can actually be asked for, from its own declared flags.
 *
 * Each axis carries two facts, and the distinction is the whole point:
 * `supports*` says the control exists at all, the list says which values.
 * A supported axis with an empty list means the model takes a *free* value —
 * 28 of 32 video models declare duration as a plain integer — and the UI must
 * offer an input rather than invent choices. Conflating the two is what made
 * the chip row report the same three durations for all 68 models.
 */
export interface ModelCapabilities {
  supportsDuration: boolean;
  /** Seconds. Empty when free-form or absent — check `supportsDuration`. */
  durations: number[];
  defaultDuration?: number | null;
  /**
   * The provider's real `[min, max]` free-form duration bound, when known.
   * The ladder builds chips up to `max` from this (H3 Max 5–15, Wan 3.0 Prime
   * 2–30) instead of a generic ladder capped at 12; the clamp keeps a staged
   * duration inside it. Absent when neither fal nor the registry states one.
   */
  durationRange?: [number, number] | null;
  supportsResolution: boolean;
  resolutions: string[];
  defaultResolution?: string | null;
  supportsAspect: boolean;
  aspects: string[];
  defaultAspect?: string | null;
  /** The model can *produce* sound, not merely accept it as input. */
  audio: boolean;
  /** Cross-field rules the flag table cannot express, verbatim from the spec. */
  constraints: string[];
  /**
   * Media roles this model cannot take on the selected route, by wire name.
   *
   * Empty until a route is chosen. Drives the greyed-out slots: the use case
   * says the job has an End Frame, this says whether the model has anywhere
   * to put it.
   */
  unsupportedRoles: string[];
}

export interface Model {
  id: string;
  displayName: string;
  modality: Modality;
  routes: Route[];
  isLaunch: boolean;
  /** One-line description in the model picker. */
  subtitle?: string;
  /**
   * Always present from the shell. Optional only so mock data and a
   * shell-less browser session still typecheck; `capabilitiesFor` treats an
   * absent value as "unknown", never as a set of plausible defaults.
   */
  capabilities?: ModelCapabilities;
}

export interface PresetVariant {
  modelId: string;
  /** Preview media generated by us. Never a third-party CDN URL. */
  previewUrl?: string;
}

export interface PresetFamily {
  id: string;
  displayName: string;
  category: string;
  tags: string[];
  description: string;
  /** Absent means the family is model-agnostic and compiles for anything. */
  variants?: PresetVariant[];
}


export interface CostEstimate {
  usd: number;
  /** Human-readable derivation, e.g. "8s x 720p at $0.30/s". */
  basis: string;
  minimumApplied?: boolean;
}

/**
 * Where the prices on screen came from, so the spend meter can say how old they
 * are and whether they are live — never implying the bundled snapshot is
 * current.
 */
export interface PriceStatus {
  /** How many routes have a price at all. */
  routes: number;
  /** Age of the oldest displayed price, or `null` for the bundled snapshot. */
  ageSeconds: number | null;
  /** False when the last fetch failed and some prices are the bundle. */
  live: boolean;
}

/**
 * The provider status machine, normalized by Rust.
 *
 * Kept open (`string & {}`) because providers keep inventing intermediate
 * stages; an unrecognized stage must render as generic activity, not blow up
 * an exhaustive switch.
 */
export type JobStatus =
  | "waiting"
  | "queued"
  | "in_progress"
  | "completed"
  | "failed"
  | "canceled"
  | "nsfw"
  // eslint-disable-next-line @typescript-eslint/ban-types
  | (string & {});

/**
 * Deliberately the Rust `MediaRole` serde names, not friendlier UI ones.
 * A translation table between the two would be one more thing to drift, and
 * the failure mode — a role that binds to the wrong wire flag — is silent.
 */
export type MediaRole =
  | "start"
  | "end"
  | "reference"
  | "video"
  | "video_reference"
  | "audio"
  | "audio_reference";

/** Mirrors `hickeyfield_core::MediaSource`, which is `#[serde(tag = "kind")]`. */
export type MediaSource =
  | { kind: "local"; path: string }
  | { kind: "url"; url: string }
  | { kind: "data_uri"; data: string };

export interface MediaRef {
  role: MediaRole;
  source: MediaSource;
  /**
   * Display only, never sent. A `blob:` URL for instant rendering; Rust
   * ignores unknown fields, so this rides along harmlessly.
   */
  preview?: string;
  /** Local file name, shown in the slot and the reference strip tooltip. */
  name?: string;
}

export interface JobResult {
  /**
   * The provider's URL. **Signed and expiring** — fal's lapse, and Higgsfield
   * deletes results after 7 days — so this is the fallback, not the source of
   * truth. Prefer `localPath`.
   */
  url: string;
  /**
   * Absolute path in the user's library, once the bytes are on disk. This is
   * what "your results stay on this machine" actually means; rendering `url`
   * after the signature lapses leaves a blank card next to a perfectly good
   * file.
   */
  localPath?: string | null;
  kind: "image" | "video" | "audio";
  width?: number;
  height?: number;
  /** Still frame for a video result, used before the clip is playable. */
  poster?: string;
}

export interface GenSettings {
  duration: number;
  resolution: string;
  aspect: string;
  audio: boolean;
  enhance: boolean;
  seed?: number | null;
  steps?: number | null;
}

/** A shot's place in the sequence — `start`/`end` bracket the story. */
export type ShotRole = "start" | "middle" | "end";

/** A recorded continuity intent (not applied in S13): chain from shot N. */
export interface Continuity {
  lastFrameOf: number;
}

/** One shot in a storyboard plan. Mirrors the Rust `Shot` (serde camelCase). */
export interface Shot {
  title: string;
  prompt: string;
  /** S16: the per-shot beat, distinct from the shared `world`. The planner
   * composes `prompt = "{world} {action}"`; edit this to keep continuity. */
  action?: string | null;
  seconds: number;
  camera: string | null;
  modelId: string;
  role: ShotRole;
  continuity?: Continuity | null;
  /** Clamp notes: a shot narrowed toward its model's duration axis says so. */
  advisories?: string[];
  /** S15: whether this shot's model can continue from a start frame (has an
   * image-to-video route). Computed server-side; the Chain toggle defaults on
   * only when every shot is chainable. */
  chainable?: boolean;
  /** S17: whether this shot's model can bind an end frame (an `end_image_url`
   * route). The Keyframe toggle enables only when every shot is end-frame-capable,
   * computed server-side so the default matches the scheduler. */
  endFrameCapable?: boolean;
  /** S16: an optional per-shot resolution (one per set is the rule). */
  resolution?: string | null;
}

/** A whole storyboard plan, drafted from one brief. Mirrors `StoryboardPlan`. */
export interface StoryboardPlan {
  /** S16: the shared world block composed verbatim into every shot's prompt. */
  world?: string;
  brief: string;
  targetSeconds: number;
  useCase: string;
  shots: Shot[];
}

/** S16: one join's recorded continuity score. Mirrors the Rust `JoinRecord`.
 * A scoring failure carries `null` numbers (never 0) and `pass: null`. */
export interface JoinRecord {
  index: number;
  kind: "continuity" | "crossfade";
  applied: boolean;
  ssim: number | null;
  psnr: number | null;
  dy: number | null;
  du: number | null;
  dv: number | null;
  pass: boolean | null;
  attempt: number;
  /** S17: end-frame adherence — the SSIM (+ colour drift) of this shot's actual
   * last frame vs its planned still. `null` when unscored (never 0). Gated
   * against the ideal tier. */
  endSsim?: number | null;
  endPsnr?: number | null;
  endDy?: number | null;
  endDu?: number | null;
  endDv?: number | null;
  endPass?: boolean | null;
}

/** S17: one keyframe still boundary of a keyframe-anchored set. */
export interface KeyframeRecord {
  index: number;
  jobSetId?: string | null;
  /** The downloaded still PNG, once the still settles; `null` while queued /
   * running, or if it failed (the set is parked). */
  localPath?: string | null;
  /** Priced at submit; `null` when unpriced (never summed as $0). */
  estimatedUsd?: number | null;
  attempt: number;
}

/** One shot's fate in a generate-all batch. Mirrors `ShotOutcome`. */
export interface ShotOutcome {
  shotIndex: number;
  jobSetId: string | null;
  error: string | null;
  /** S15: a chained shot not yet submitted — the settled hook submits it when
   * its predecessor completes. */
  pending?: boolean;
}

/** The result of a generate-all. Mirrors `StoryboardResult`. */
export interface StoryboardResult {
  storyboardId: string;
  shots: ShotOutcome[];
}

/** A stored storyboard grouping row, for Library group headers. */
export interface Storyboard {
  id: string;
  brief: string;
  targetSeconds: number;
  planJson: string;
  createdAt: number;
  /** S16: the recorded per-join continuity scores, for the Library badges and
   * the set's minimum-score summary. Empty for an unscored or pre-S16 set. */
  joins?: JoinRecord[];
  /** S16: whether the set opted into bounded auto-retry. */
  autoRetry?: boolean;
  /** S17: the keyframe boundaries of a keyframe-anchored set (one still per shot
   * boundary). Empty for a non-keyframe set. */
  keyframes?: KeyframeRecord[];
}

/** S15: a finished, stitched storyboard ad on disk. Mirrors the Rust
 * `StoryboardRenderDto`. `actualUsd` is Σ of the member shots' actual cost
 * (null if any member is unpriced — never $0). */
export interface StoryboardRender {
  storyboardId: string;
  outputPath: string;
  width: number | null;
  height: number | null;
  seconds: number | null;
  actualUsd: number | null;
  createdAt: number;
}

/** S15: a render progress tick from the `storyboard:render` event. */
export interface RenderProgress {
  storyboardId: string;
  percent: number;
  done: boolean;
}

/** S15: render options passed to `renderStoryboard`. */
export interface RenderOptions {
  overlapSeconds?: number | null;
}

export interface JobSet {
  id: string;
  modelId: string;
  status: JobStatus;
  prompt: string;
  enhancedPrompt?: string | null;
  createdAt: string;
  results: JobResult[];
  route: Route;
  /** null means the provider published no price for this call. Not zero. */
  estimatedUsd: number | null;
  actualUsd?: number | null;
  presetId?: string | null;
  presetName?: string | null;
  settings?: GenSettings;
  media?: MediaRef[];
  /** Which enhancer rewrote the prompt. Higgsfield does not expose this. */
  enhancerVersion?: string | null;
  /**
   * Why the prompt was not rewritten, when it was not. Rendered next to the
   * Enhance toggle so "enhance was on and nothing changed" is never silent.
   */
  enhanceNote?: string | null;
  /**
   * Things that happened which you should know but which did not fail the
   * job — most often a setting this endpoint has no field for. Distinct from
   * `failReason` (the job died) and `enhanceNote` (about the rewriter).
   */
  advisories?: string[];
  failReason?: string | null;
  /** The storyboard this job is a shot of, when it was generated as a set. */
  storyboardId?: string | null;
  /** This job's 0-based position within its storyboard. */
  shotIndex?: number | null;
}

/**
 * How suitable a local Ollama model is for prompt enhancement, decided by Rust.
 * Not a filter — any model still runs if picked — but a ranking the picker uses
 * to lead with a fast go-to and warn about the rest. Mirrors the Rust
 * `ModelTier` (serialized lowercase).
 */
export type ModelTier = "recommended" | "neutral" | "discouraged";

/**
 * One installed Ollama model plus Rust's suitability verdict. The list arrives
 * already sorted (Recommended→Neutral→Discouraged); the UI consumes it untouched
 * and takes `[0]` as the default, so what the picker shows == what submit sends.
 */
export interface LocalModel {
  name: string;
  tier: ModelTier;
}

/**
 * The user's explicit enhancer choice. `null`/omitted means "decide for me":
 * the shell auto-detects. `backend` is `"ollama"` or `"openai"`; `model` is the
 * installed Ollama tag or the hosted model id (required for both).
 */
export interface RewriterChoice {
  backend: string;
  model?: string;
}

export interface SubmitInput {
  modelId: string;
  routeId: string;
  prompt: string;
  presetId: string | null;
  settings: GenSettings;
  media: MediaRef[];
  /** null means auto — the shell picks from what is actually reachable. */
  rewriter?: RewriterChoice | null;
  /**
   * The exact prompt the user previewed and possibly edited. When present and
   * non-empty the shell sends it VERBATIM and does not re-run the enhancer —
   * the previewed text already carries the camera clause. Absent on the quick
   * one-click Generate, which enhances silently as before.
   */
  finalPrompt?: string | null;
}

/**
 * What the enhancer would produce for a prompt, shown before any money is spent.
 * Mirrors the Rust `PreviewDto`: `prompt` is the full wire text (camera clause +
 * any rewrite), `original` the user's own words, `enhanced` set only when a
 * rewrite actually changed the text, `note` the honest reason when it did not.
 */
export interface PromptPreview {
  prompt: string;
  original: string;
  enhanced?: string | null;
  version?: string | null;
  note?: string | null;
}

/**
 * A use case slug from Rust — `text-to-video`, `edit-video`, …
 *
 * Replaces the old `create | edit | motion` triple, which named Higgsfield's
 * surfaces rather than jobs and filtered nothing: every model was offered under
 * every tab, so you could sit in "Edit Video" with a clip attached, pick a
 * text-only model, and only find out after submitting.
 */
export type WorkspaceTab = string;

export interface UseCase {
  slug: string;
  label: string;
  blurb: string;
  /** `[role, required]`. A required slot the job cannot run without. */
  slots: [string, boolean][];
  requiresMedia: boolean;
}
